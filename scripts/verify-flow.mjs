const logs=await call('logs?code='+station.code,null,'admin');assert.equal(logs.events.filter(e=>e.type==='request').length,2);assert.equal(logs.events.filter(e=>e.type==='confirm').length,2);checks+=2;
await call('request',{code:station.code,target:'active',version:data.stations[0].version},'admin');
